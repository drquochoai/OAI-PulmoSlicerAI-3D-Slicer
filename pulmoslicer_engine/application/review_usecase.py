"""AP06: only the clinician-facing UI authority may issue human review records."""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from uuid import uuid4

from pulmoslicer_engine.domain.review_record import ReviewRecord, ReviewStatus


class ReviewAuthority(str, Enum):
    CLINICIAN_UI = "CLINICIAN_UI"
    WORKER = "WORKER"
    IMPORT = "IMPORT"


class ReviewAuthorizationError(PermissionError):
    """A non-human or untrusted boundary attempted to create approval."""


def record_review(
    authority: ReviewAuthority,
    artifact_sha256: str,
    reviewer_id: str,
    status: ReviewStatus,
    reason: str,
) -> ReviewRecord:
    if authority is not ReviewAuthority.CLINICIAN_UI:
        raise ReviewAuthorizationError("only CLINICIAN_UI may issue review decisions")
    if status is ReviewStatus.STALE:
        raise ReviewAuthorizationError("STALE is generated by dependency invalidation, not user approval")
    return ReviewRecord(
        review_id=str(uuid4()),
        artifact_sha256=artifact_sha256,
        reviewer_id=reviewer_id,
        status=status,
        reason=reason,
        created_at=datetime.now(timezone.utc).isoformat(),
    )

